-- Referral redesign and automatic reactivation.
--
-- Run after alter_loyalty_point_lots.sql.  It is safe to run once on the
-- current production database: it does not change historical rewards or
-- existing global promo codes.

-- Personal coupons are deliberately separate from public promo codes: a
-- coupon belongs to exactly one customer and cannot be redeemed by somebody
-- who received its id from a forwarded message.
create table if not exists public.coupons (
  id text primary key,
  tg_user_id bigint not null references public.customer_profiles (tg_user_id) on delete cascade,
  kind text not null default 'percent',
  value numeric not null,
  min_order_sum numeric not null default 0,
  max_discount numeric null,
  source text not null,
  referral_id bigint null references public.referrals (id) on delete set null,
  campaign_key text null,
  is_used boolean not null default false,
  used_order_id uuid null references public.orders (id) on delete set null,
  expires_at timestamptz null,
  created_at timestamptz not null default now(),
  used_at timestamptz null,
  constraint coupons_kind_check check (kind in ('percent', 'fixed')),
  constraint coupons_value_check check (value > 0),
  constraint coupons_min_order_sum_check check (min_order_sum >= 0),
  constraint coupons_max_discount_check check (max_discount is null or max_discount > 0),
  constraint coupons_used_at_check check ((is_used and used_at is not null) or (not is_used)),
  constraint coupons_used_order_check check (used_order_id is null or is_used)
);

-- A few early installations had a manually created coupons table. Keep this
-- migration additive when it encounters one.
alter table public.coupons
  add column if not exists campaign_key text null;

create index if not exists coupons_customer_available_idx
  on public.coupons (tg_user_id, expires_at, created_at)
  where not is_used;

-- Referral binding can be retried (for example, after a Telegram webhook
-- timeout), but a referred customer must only ever receive one first-order
-- coupon.
create unique index if not exists coupons_referral_first_order_unique_idx
  on public.coupons (referral_id)
  where source = 'referral_first_order';

create unique index if not exists coupons_reactivation_cycle_unique_idx
  on public.coupons (tg_user_id, source, campaign_key)
  where source = 'reactivation_30d' and campaign_key is not null;

-- One reactivation campaign corresponds to one specific last completed
-- purchase.  A later purchase creates a different eligibility cycle; repeated
-- cron invocations cannot create or send duplicate campaigns for the same one.
create table if not exists public.customer_reactivation_campaigns (
  id bigint generated by default as identity primary key,
  tg_user_id bigint not null references public.customer_profiles (tg_user_id) on delete cascade,
  last_completed_order_at timestamptz not null,
  -- Kept as text without an FK so this migration is compatible with both
  -- legacy UUID coupon ids and fresh text-id installations.
  coupon_id text not null unique,
  expires_at timestamptz not null,
  send_attempts integer not null default 0 check (send_attempts >= 0),
  last_send_attempt_at timestamptz null,
  sent_at timestamptz null,
  cancelled_at timestamptz null,
  created_at timestamptz not null default now(),
  unique (tg_user_id, last_completed_order_at)
);

alter table public.customer_reactivation_campaigns
  add column if not exists cancelled_at timestamptz null;

create index if not exists customer_reactivation_campaigns_pending_idx
  on public.customer_reactivation_campaigns (sent_at, expires_at, created_at)
  where sent_at is null and cancelled_at is null;

-- Records whether the referrer received the Telegram message.  Rewarding is
-- still ledger-idempotent; this column avoids messages on ordinary retries.
alter table public.customer_profiles
  add column if not exists tg_first_name text null;

alter table public.referrals
  add column if not exists inviter_reward_notified_at timestamptz null;

alter table public.coupons enable row level security;
alter table public.customer_reactivation_campaigns enable row level security;
revoke all on public.coupons from anon, authenticated;
revoke all on public.customer_reactivation_campaigns from anon, authenticated;

notify pgrst, 'reload schema';

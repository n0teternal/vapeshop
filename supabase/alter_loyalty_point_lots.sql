-- Run this AFTER alter_loyalty_monthly_tiers.sql.
-- It replaces the old 60-day expiry function, including its previous
-- ambiguity fix, so alter_loyalty_expiry_function_fix.sql is not needed when
-- this migration is applied.
--
-- Every positive points accrual is a separate lot. A lot expires 30 days
-- after it is created; a later order never extends its expiry. Write-offs use
-- the lots with the nearest expiry first (FIFO by expiry and then id).

create table if not exists public.loyalty_point_lots (
  id bigint generated by default as identity primary key,
  tg_user_id bigint not null references public.customer_profiles (tg_user_id) on delete cascade,
  source_transaction_id bigint null unique references public.loyalty_transactions (id) on delete restrict,
  total_points integer not null check (total_points > 0),
  remaining_points integer not null check (remaining_points >= 0 and remaining_points <= total_points),
  expires_at timestamptz not null,
  legacy_balance boolean not null default false,
  created_at timestamptz not null default now()
);

-- There can be exactly one migration lot per customer. It keeps the balance
-- that existed before this rule live for 30 days after rollout instead of
-- retroactively burning it.
create unique index if not exists loyalty_point_lots_legacy_user_unique_idx
  on public.loyalty_point_lots (tg_user_id)
  where legacy_balance;

create index if not exists loyalty_point_lots_expiry_idx
  on public.loyalty_point_lots (tg_user_id, expires_at, id)
  where remaining_points > 0;

create table if not exists public.loyalty_point_lot_spends (
  order_id uuid not null references public.orders (id) on delete cascade,
  lot_id bigint not null references public.loyalty_point_lots (id) on delete restrict,
  points integer not null check (points > 0),
  primary key (order_id, lot_id)
);

create index if not exists loyalty_point_lot_spends_lot_idx
  on public.loyalty_point_lot_spends (lot_id);

alter table public.loyalty_point_lots enable row level security;
alter table public.loyalty_point_lot_spends enable row level security;
revoke all on public.loyalty_point_lots from anon, authenticated;
revoke all on public.loyalty_point_lot_spends from anon, authenticated;

-- Move each current balance into one clearly labelled transition lot. Pending
-- orders that already reserve a points discount are allocated from that lot,
-- so reducing their discount later correctly returns the points.
with active_order_spend as (
  select
    transaction_row.tg_user_id,
    coalesce(sum(-transaction_row.delta_points), 0)::integer as points
  from public.loyalty_transactions as transaction_row
  join public.orders as order_row on order_row.id = transaction_row.order_id
  where transaction_row.kind = 'order_points_spend'
    and transaction_row.delta_points < 0
    and order_row.status in ('new', 'processing')
  group by transaction_row.tg_user_id
)
insert into public.loyalty_point_lots (
  tg_user_id,
  total_points,
  remaining_points,
  expires_at,
  legacy_balance,
  created_at
)
select
  profile.tg_user_id,
  greatest(profile.bonus_points, 0) + coalesce(active_order_spend.points, 0),
  greatest(profile.bonus_points, 0),
  now() + interval '30 days',
  true,
  now()
from public.customer_profiles as profile
left join active_order_spend on active_order_spend.tg_user_id = profile.tg_user_id
where greatest(profile.bonus_points, 0) + coalesce(active_order_spend.points, 0) > 0
  and not exists (
    select 1
    from public.loyalty_point_lots as existing_lot
    where existing_lot.tg_user_id = profile.tg_user_id
      and existing_lot.legacy_balance
  );

insert into public.loyalty_point_lot_spends (order_id, lot_id, points)
select
  transaction_row.order_id,
  legacy_lot.id,
  -transaction_row.delta_points
from public.loyalty_transactions as transaction_row
join public.orders as order_row on order_row.id = transaction_row.order_id
join public.loyalty_point_lots as legacy_lot
  on legacy_lot.tg_user_id = transaction_row.tg_user_id
  and legacy_lot.legacy_balance
where transaction_row.kind = 'order_points_spend'
  and transaction_row.delta_points < 0
  and order_row.status in ('new', 'processing')
on conflict (order_id, lot_id) do nothing;

update public.customer_profiles as profile
set
  loyalty_expires_at = case when profile.bonus_points > 0 then legacy_lot.expires_at else null end,
  loyalty_notice_45_sent_at = null,
  loyalty_notice_59_sent_at = null,
  updated_at = now()
from public.loyalty_point_lots as legacy_lot
where legacy_lot.tg_user_id = profile.tg_user_id
  and legacy_lot.legacy_balance;

-- Recalculate the profile cache from lots and move the next-expiry marker to
-- the first non-empty lot. The cache keeps ordinary reads inexpensive.
create or replace function public.loyalty_sync_point_balance(
  p_tg_user_id bigint
)
returns table (
  bonus_points integer,
  loyalty_expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_balance integer;
  v_next_expiry timestamptz;
begin
  select
    coalesce(sum(lot.remaining_points), 0)::integer,
    min(lot.expires_at) filter (where lot.remaining_points > 0)
  into v_balance, v_next_expiry
  from public.loyalty_point_lots as lot
  where lot.tg_user_id = p_tg_user_id;

  update public.customer_profiles as profile
  set
    bonus_points = v_balance,
    loyalty_expires_at = v_next_expiry,
    loyalty_notice_45_sent_at = case
      when profile.loyalty_expires_at is distinct from v_next_expiry then null
      else profile.loyalty_notice_45_sent_at
    end,
    loyalty_notice_59_sent_at = case
      when profile.loyalty_expires_at is distinct from v_next_expiry then null
      else profile.loyalty_notice_59_sent_at
    end,
    updated_at = now()
  where profile.tg_user_id = p_tg_user_id;

  return query select v_balance, v_next_expiry;
end;
$$;

create or replace function public.loyalty_expire_points(
  p_tg_user_id bigint
)
returns table (
  expired_points integer,
  bonus_points integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.customer_profiles%rowtype;
  v_expired_points integer := 0;
  v_balance integer := 0;
  v_status_expired boolean;
begin
  select * into v_profile
  from public.customer_profiles
  where tg_user_id = p_tg_user_id
  for update;
  if not found then
    raise exception 'loyalty profile % not found', p_tg_user_id using errcode = 'P0002';
  end if;

  with due_lots as (
    select id, remaining_points
    from public.loyalty_point_lots
    where tg_user_id = p_tg_user_id
      and remaining_points > 0
      and expires_at <= now()
    for update
  ), expired_lots as (
    update public.loyalty_point_lots as lot
    set remaining_points = 0
    from due_lots
    where lot.id = due_lots.id
    returning due_lots.remaining_points
  )
  select coalesce(sum(remaining_points), 0)::integer
  into v_expired_points
  from expired_lots;

  if v_expired_points > 0 then
    insert into public.loyalty_transactions (tg_user_id, delta_points, kind, comment, created_at)
    values (
      p_tg_user_id,
      -v_expired_points,
      'points_expired',
      'Expired point lots after 30 days',
      now()
    );
  end if;

  select synced.bonus_points into v_balance
  from public.loyalty_sync_point_balance(p_tg_user_id) as synced;

  v_status_expired := v_profile.current_cashback_level > 0
    and (v_profile.last_order_date is null or v_profile.last_order_date <= now() - interval '60 days');
  if v_status_expired then
    update public.customer_profiles
    set current_cashback_level = 0, monthly_spent = 0, updated_at = now()
    where tg_user_id = p_tg_user_id;
  end if;

  return query select v_expired_points, v_balance;
end;
$$;

create or replace function public.loyalty_set_order_points_spend(
  p_tg_user_id bigint,
  p_order_id uuid,
  p_points_to_spend integer
)
returns table (
  previous_points integer,
  points_to_spend integer,
  bonus_points integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.customer_profiles%rowtype;
  v_transaction public.loyalty_transactions%rowtype;
  v_lot record;
  v_previous_points integer := 0;
  v_requested_points integer := greatest(coalesce(p_points_to_spend, 0), 0);
  v_available_points integer := 0;
  v_remaining_to_spend integer;
  v_take integer;
  v_balance integer := 0;
  v_had_transaction boolean := false;
begin
  perform public.loyalty_expire_points(p_tg_user_id);

  select * into v_profile
  from public.customer_profiles
  where tg_user_id = p_tg_user_id
  for update;
  if not found then
    raise exception 'loyalty profile % not found', p_tg_user_id using errcode = 'P0002';
  end if;

  select * into v_transaction
  from public.loyalty_transactions
  where tg_user_id = p_tg_user_id
    and kind = 'order_points_spend'
    and order_id = p_order_id
  for update;
  if found then
    v_had_transaction := true;
    v_previous_points := greatest(-v_transaction.delta_points, 0);

    update public.loyalty_point_lots as lot
    set remaining_points = lot.remaining_points + allocation.points
    from public.loyalty_point_lot_spends as allocation
    where allocation.order_id = p_order_id
      and allocation.lot_id = lot.id;
    delete from public.loyalty_point_lot_spends where order_id = p_order_id;
  end if;

  select synced.bonus_points into v_available_points
  from public.loyalty_sync_point_balance(p_tg_user_id) as synced;
  if v_requested_points > v_available_points then
    raise exception 'not enough loyalty points' using errcode = 'P0001';
  end if;

  v_remaining_to_spend := v_requested_points;
  for v_lot in
    select id, remaining_points
    from public.loyalty_point_lots
    where tg_user_id = p_tg_user_id
      and remaining_points > 0
      and expires_at > now()
    order by expires_at asc, id asc
    for update
  loop
    exit when v_remaining_to_spend = 0;
    v_take := least(v_lot.remaining_points, v_remaining_to_spend);
    update public.loyalty_point_lots
    set remaining_points = remaining_points - v_take
    where id = v_lot.id;
    insert into public.loyalty_point_lot_spends (order_id, lot_id, points)
    values (p_order_id, v_lot.id, v_take);
    v_remaining_to_spend := v_remaining_to_spend - v_take;
  end loop;

  if v_remaining_to_spend <> 0 then
    raise exception 'not enough loyalty points' using errcode = 'P0001';
  end if;

  if v_had_transaction and v_requested_points = 0 then
    delete from public.loyalty_transactions where id = v_transaction.id;
  elsif v_had_transaction then
    update public.loyalty_transactions
    set delta_points = -v_requested_points
    where id = v_transaction.id;
  elsif v_requested_points > 0 then
    insert into public.loyalty_transactions (tg_user_id, delta_points, kind, order_id, created_at)
    values (p_tg_user_id, -v_requested_points, 'order_points_spend', p_order_id, now());
  end if;

  select synced.bonus_points into v_balance
  from public.loyalty_sync_point_balance(p_tg_user_id) as synced;
  return query select v_previous_points, v_requested_points, v_balance;
end;
$$;

create or replace function public.loyalty_apply_points_transaction(
  p_tg_user_id bigint,
  p_delta_points integer,
  p_kind text,
  p_order_id uuid default null,
  p_referral_id bigint default null,
  p_comment text default null,
  p_reset_expiry boolean default false
)
returns table (
  applied boolean,
  bonus_points integer,
  loyalty_expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.customer_profiles%rowtype;
  v_existing_id bigint;
  v_transaction_id bigint;
  v_lot record;
  v_remaining_to_debit integer;
  v_take integer;
  v_balance integer := 0;
  v_next_expiry timestamptz;
begin
  if p_delta_points = 0 then
    raise exception 'loyalty delta must not be zero' using errcode = '22023';
  end if;

  perform public.loyalty_expire_points(p_tg_user_id);

  select * into v_profile
  from public.customer_profiles
  where tg_user_id = p_tg_user_id
  for update;
  if not found then
    raise exception 'loyalty profile % not found', p_tg_user_id using errcode = 'P0002';
  end if;

  if p_referral_id is not null and p_kind in ('referral_inviter_bonus', 'referral_invitee_bonus') then
    select id into v_existing_id
    from public.loyalty_transactions
    where tg_user_id = p_tg_user_id
      and kind = p_kind
      and referral_id = p_referral_id;
    if found then
      return query select false, v_profile.bonus_points, v_profile.loyalty_expires_at;
      return;
    end if;
  end if;

  if p_delta_points < 0 then
    v_remaining_to_debit := -p_delta_points;
    if v_remaining_to_debit > v_profile.bonus_points then
      raise exception 'not enough loyalty points' using errcode = 'P0001';
    end if;

    for v_lot in
      select id, remaining_points
      from public.loyalty_point_lots
      where tg_user_id = p_tg_user_id
        and remaining_points > 0
        and expires_at > now()
      order by expires_at asc, id asc
      for update
    loop
      exit when v_remaining_to_debit = 0;
      v_take := least(v_lot.remaining_points, v_remaining_to_debit);
      update public.loyalty_point_lots
      set remaining_points = remaining_points - v_take
      where id = v_lot.id;
      v_remaining_to_debit := v_remaining_to_debit - v_take;
    end loop;

    if v_remaining_to_debit <> 0 then
      raise exception 'not enough loyalty points' using errcode = 'P0001';
    end if;
  end if;

  insert into public.loyalty_transactions (
    tg_user_id, delta_points, kind, order_id, referral_id, comment, created_at
  ) values (
    p_tg_user_id, p_delta_points, p_kind, p_order_id, p_referral_id, p_comment, now()
  ) returning id into v_transaction_id;

  if p_delta_points > 0 then
    insert into public.loyalty_point_lots (
      tg_user_id, source_transaction_id, total_points, remaining_points, expires_at, created_at
    ) values (
      p_tg_user_id, v_transaction_id, p_delta_points, p_delta_points, now() + interval '30 days', now()
    );
  end if;

  -- `p_reset_expiry` is kept only for API compatibility. Individual lot
  -- expiry is never reset by a later order or a manual transaction.

  select synced.bonus_points, synced.loyalty_expires_at
  into v_balance, v_next_expiry
  from public.loyalty_sync_point_balance(p_tg_user_id) as synced;
  return query select true, v_balance, v_next_expiry;
end;
$$;

create or replace function public.loyalty_complete_order(
  p_tg_user_id bigint,
  p_order_id uuid,
  p_cashback_base numeric
)
returns table (
  applied boolean,
  cashback_points integer,
  cashback_percent integer,
  total_spent numeric,
  bonus_points integer,
  loyalty_expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.customer_profiles%rowtype;
  v_existing public.loyalty_transactions%rowtype;
  v_now timestamptz := now();
  v_completed_at timestamptz;
  v_percent integer;
  v_cashback_points integer;
  v_new_total numeric;
  v_monthly_spent numeric;
  v_earned_level integer;
  v_new_level integer;
  v_transaction_id bigint;
  v_balance integer := 0;
  v_next_expiry timestamptz;
begin
  perform public.loyalty_expire_points(p_tg_user_id);

  select * into v_profile
  from public.customer_profiles
  where tg_user_id = p_tg_user_id
  for update;
  if not found then
    raise exception 'loyalty profile % not found', p_tg_user_id using errcode = 'P0002';
  end if;

  update public.orders
  set completed_at = coalesce(completed_at, v_now)
  where id = p_order_id
    and tg_user_id = p_tg_user_id
    and status = 'done'
  returning completed_at into v_completed_at;
  if not found then
    raise exception 'completed order % not found for loyalty', p_order_id using errcode = 'P0002';
  end if;

  select * into v_existing
  from public.loyalty_transactions
  where tg_user_id = p_tg_user_id
    and kind = 'order_cashback'
    and order_id = p_order_id;
  if found then
    return query select
      false,
      v_existing.delta_points,
      v_profile.current_cashback_level,
      v_profile.total_spent,
      v_profile.bonus_points,
      v_profile.loyalty_expires_at;
    return;
  end if;

  v_percent := v_profile.current_cashback_level;
  v_cashback_points := round(greatest(coalesce(p_cashback_base, 0), 0) * v_percent / 100.0)::integer;
  v_new_total := v_profile.total_spent + greatest(coalesce(p_cashback_base, 0), 0);

  insert into public.loyalty_transactions (
    tg_user_id, delta_points, kind, order_id, comment, created_at
  ) values (
    p_tg_user_id, v_cashback_points, 'order_cashback', p_order_id,
    format('%s%% cashback from order', v_percent), v_now
  ) returning id into v_transaction_id;

  if v_cashback_points > 0 then
    insert into public.loyalty_point_lots (
      tg_user_id, source_transaction_id, total_points, remaining_points, expires_at, created_at
    ) values (
      p_tg_user_id, v_transaction_id, v_cashback_points, v_cashback_points,
      v_now + interval '30 days', v_now
    );
  end if;

  select coalesce(sum(coalesce(order_row.total_after_discount, order_row.total_price)), 0)
  into v_monthly_spent
  from public.orders as order_row
  where order_row.tg_user_id = p_tg_user_id
    and order_row.status = 'done'
    and order_row.completed_at >= v_now - interval '30 days';

  v_earned_level := case
    when v_monthly_spent >= 10000 then 7
    when v_monthly_spent >= 5000 then 5
    when v_monthly_spent >= 3000 then 3
    else 0
  end;
  v_new_level := greatest(v_profile.current_cashback_level, v_earned_level);

  update public.customer_profiles
  set
    total_spent = v_new_total,
    monthly_spent = v_monthly_spent,
    current_cashback_level = v_new_level,
    last_order_date = v_completed_at,
    updated_at = v_now
  where tg_user_id = p_tg_user_id;

  select synced.bonus_points, synced.loyalty_expires_at
  into v_balance, v_next_expiry
  from public.loyalty_sync_point_balance(p_tg_user_id) as synced;

  return query select true, v_cashback_points, v_percent, v_new_total, v_balance, v_next_expiry;
end;
$$;


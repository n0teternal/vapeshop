-- Privacy-minimal product analytics for the Mini App.
--
-- Stores only the authenticated customer id, city, event name and time. It
-- deliberately does not store address, cart contents, product views, search
-- phrases, Telegram profile fields or message text.

create table if not exists public.product_analytics_events (
  id bigint generated by default as identity primary key,
  customer_id bigint not null,
  city_slug text null,
  event_name text not null,
  occurred_at timestamptz not null default now(),
  constraint product_analytics_events_city_check
    check (city_slug is null or city_slug in ('blg', 'vvo')),
  constraint product_analytics_events_name_check
    check (event_name in ('app_open', 'catalog_view', 'cart_add', 'checkout_view', 'order_created'))
);

create index if not exists product_analytics_events_occurred_at_idx
  on public.product_analytics_events (occurred_at desc);

create index if not exists product_analytics_events_customer_event_idx
  on public.product_analytics_events (customer_id, event_name, occurred_at desc);

create index if not exists product_analytics_events_city_occurred_at_idx
  on public.product_analytics_events (city_slug, occurred_at desc);

-- The state prevents an otherwise helpful post-order question from becoming
-- intrusive. A customer in the deterministic sample sees it only once after
-- opening the app, regardless of how many orders they make.
create table if not exists public.app_feedback_prompt_states (
  customer_id bigint primary key,
  last_prompted_at timestamptz null,
  last_dismissed_at timestamptz null,
  last_responded_at timestamptz null,
  prompt_count integer not null default 0 check (prompt_count >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_feedback_responses (
  id bigint generated by default as identity primary key,
  customer_id bigint not null,
  city_slug text null,
  prompted_at timestamptz not null,
  rating smallint not null check (rating between 1 and 5),
  comment text null check (comment is null or char_length(comment) <= 600),
  created_at timestamptz not null default now(),
  constraint app_feedback_responses_city_check
    check (city_slug is null or city_slug in ('blg', 'vvo')),
  constraint app_feedback_responses_one_per_prompt unique (customer_id, prompted_at)
);

create index if not exists app_feedback_responses_created_at_idx
  on public.app_feedback_responses (created_at desc);

create index if not exists app_feedback_responses_customer_created_at_idx
  on public.app_feedback_responses (customer_id, created_at desc);

alter table public.product_analytics_events enable row level security;
alter table public.app_feedback_prompt_states enable row level security;
alter table public.app_feedback_responses enable row level security;

revoke all on public.product_analytics_events from anon, authenticated;
revoke all on public.app_feedback_prompt_states from anon, authenticated;
revoke all on public.app_feedback_responses from anon, authenticated;

notify pgrst, 'reload schema';
